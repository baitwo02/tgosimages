        else
            printf '  ./build.sh platform qemu-%s [os] [options]\n' "${usage_arch}"
        fi
    else
        printf '  scripts/qemu.sh <command> <os> [options]\n'
        printf '\n'
        printf 'Commands:\n'
        printf '  aarch64                           Build all OS targets for AArch64 architecture\n'
        printf '  x86_64                            Build all OS targets for x86_64 architecture\n'
        printf '  riscv64                           Build all OS targets for RISC-V architecture\n'
        printf '  all                               Build all supported architectures and OS targets\n'
        printf '  help, -h, --help                  Display this help information\n'
        printf '  clean                             Clean build output artifacts\n'
    fi
    printf '\n'
    printf 'OS Targets:\n'
    printf '  linux                             Build the Linux OS\n'
    printf '  arceos                            Build the ArceOS OS (temporarily disabled for QEMU)\n'
    printf '  nimbos                            Build the NimbOS OS\n'
    printf '  zephyr                            Build the Zephyr guest image (aarch64 only)\n'
    printf '  freertos                          Build the FreeRTOS guest image (aarch64 only)\n'
    printf '  all                               Build all OS targets (default)\n'
    printf '  clean                             Clean build output artifacts\n'
    printf '\n'
    printf 'Options:\n'
    printf '  Optional, all options will be directly passed to the specific OS build script\n'
    printf '  --rootfs <list>                   Override default rootfs builders (busybox,alpine,debian)\n'
    printf '\n'
    printf 'Rootfs Packaging:\n'
    printf '  * Rootfs is generated by default for build commands.\n'
    printf '  * Rootfs is not generated for help or clean commands.\n'
    printf '  * Build outputs from all selected OS targets are staged together into /guest/<os>/ inside one rootfs.\n'
    printf '  * Generated rootfs artifacts are stored directly under IMAGES/rootfs.\n'
    printf '\n'
    printf 'Examples:\n'
    if [[ -n "${usage_arch}" ]]; then
        if [[ "${usage_arch}" == "all" ]]; then
            printf '  ./build.sh platform qemu linux\n'
            printf '  ./build.sh platform qemu all --rootfs busybox,alpine,debian\n'
        else
            printf '  ./build.sh platform qemu-%s linux\n' "${usage_arch}"
            printf '  ./build.sh platform qemu-%s all --rootfs busybox,alpine,debian\n' "${usage_arch}"
        fi
    else
        printf '  scripts/qemu.sh aarch64 linux     # Build ARM64 Linux\n'
        printf '  scripts/qemu.sh x86_64 arceos     # Build x86_64 ArceOS (temporarily disabled for QEMU)\n'
        printf '  scripts/qemu.sh riscv64 nimbos    # Build RISC-V NimbOS\n'
        printf '  scripts/qemu.sh aarch64 all --rootfs busybox,alpine,debian\n'
        printf '  scripts/qemu.sh riscv64 all       # Build all OS targets for RISC-V\n'
    fi
}

qemu_arch_images_dir() {
    local arch="$1"
    printf '%s\n' "${ROOT_DIR}/IMAGES/qemu-${arch}"
}

linux() {
    info "Cloning ${ARCH} Linux source repository $LINUX_REPO_URL"
    clone_repository "$LINUX_REPO_URL" "$LINUX_SRC_DIR"

    info "Applying patches..."
    apply_patches "$LINUX_PATCH_DIR" "$LINUX_SRC_DIR"

    info "Starting to build ${ARCH} Linux OS..."
    local commands=("$@")
    case "${ARCH}" in
        aarch64)
            local linux_arch="arm64"
            local cross_compile="${AARCH64_CROSS_COMPILE:-aarch64-linux-gnu-}"
            local defconfig="defconfig"
            local kimg_subpath="arch/arm64/boot/Image"
            ;;
        riscv64)
            local linux_arch="riscv"
            local cross_compile="${RISCV64_CROSS_COMPILE:-riscv64-linux-gnu-}"
            local defconfig="defconfig"
            local kimg_subpath="arch/riscv/boot/Image"
            ;;
        x86_64)
            local linux_arch="x86"
            local cross_compile="${X86_CROSS_COMPILE:-}"
            local defconfig="x86_64_defconfig"
            local kimg_subpath="arch/x86/boot/bzImage"
            ;;
        *)
            die "Unsupported Linux architecture: ${ARCH}"
            ;;
    esac
    
    pushd "${LINUX_SRC_DIR}" >/dev/null

    # info "Cleaning Linux: make distclean"
    # make distclean || true

    if [[ "$@" != *"clean"* ]]; then
        if [[ ${#commands[@]} -eq 0 ]] || [[ "${commands[0]}" == "all" ]]; then
            info "Configuring Linux: make ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} ${defconfig}"
            make ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "${defconfig}"
        fi
        
        info "Building Linux: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} ${commands[@]}"
        make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "${commands[@]}"
        
        popd >/dev/null

        # If it's a full build, copy the image and create the root filesystem
        if [[ ${#commands[@]} -eq 0 ]] || [[ "${commands[0]}" == "all" ]]; then
            LINUX_IMAGES_DIR="$(qemu_arch_images_dir "${ARCH}")/linux"
            mkdir -p "${LINUX_IMAGES_DIR}"
            KIMG_PATH="${LINUX_SRC_DIR}/${kimg_subpath}"
            [[ -f "${KIMG_PATH}" ]] || die "Kernel image not found: ${KIMG_PATH}"
            info "Copying image: ${KIMG_PATH} -> ${LINUX_IMAGES_DIR}/linux-qemu"
            cp -f "${KIMG_PATH}" "${LINUX_IMAGES_DIR}/linux-qemu"
            
        fi
    else
        info "Building Linux: make -j$(nproc) ARCH=${linux_arch} CROSS_COMPILE=${cross_compile} clean"
        make -j"$(nproc)" ARCH="${linux_arch}" CROSS_COMPILE="${cross_compile}" "clean"
        LINUX_IMAGES_DIR="$(qemu_arch_images_dir "${ARCH}")/linux"
        info "Removing ${LINUX_IMAGES_DIR}/*"
        rm -rf "${LINUX_IMAGES_DIR}"/* || true
    fi
}

