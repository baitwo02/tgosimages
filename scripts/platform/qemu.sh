nimbos() {
    local qemu_images_dir
    local nimbos_images_dir

    qemu_images_dir="$(qemu_arch_images_dir "${ARCH}")"
    nimbos_images_dir="${qemu_images_dir}/nimbos"

    bash "${SCRIPT_DIR}/../os/nimbos.sh" "$ARCH" --images-dir "${nimbos_images_dir}" --image-name "nimbos-qemu" "$@"

    if [[ "$@" == *"clean"* ]]; then
        rm -rf "${nimbos_images_dir}" || true
    fi
}

zephyr() {
    local zephyr_images_dir

    zephyr_images_dir="$(qemu_arch_images_dir "${ARCH}")/zephyr"

    if [[ "${ARCH}" != "aarch64" ]]; then
        die "Zephyr guest build is currently only supported for qemu aarch64"
    fi

    bash "${SCRIPT_DIR}/../os/zephyr.sh" qemu-aarch64 --images-dir "${zephyr_images_dir}" --image-name "zephyr-qemu" "$@"
}

freertos() {
    local qemu_images_dir
    local freertos_images_dir

    qemu_images_dir="$(qemu_arch_images_dir "${ARCH}")"
    freertos_images_dir="${qemu_images_dir}/freertos"

    if [[ "${ARCH}" != "aarch64" ]]; then
        die "FreeRTOS guest build is currently only supported for qemu aarch64"
    fi

    if [[ "$@" != *"clean"* ]]; then
        bash "${SCRIPT_DIR}/../os/freertos.sh" qemu-aarch64 --images-dir "${freertos_images_dir}" --image-name "freertos-qemu"
    else
        bash "${SCRIPT_DIR}/../os/freertos.sh" qemu-aarch64 clean --images-dir "${freertos_images_dir}" --image-name "freertos-qemu"
        rm -rf "${freertos_images_dir}" || true
    fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    cmd="${1:-}"
    shift 1 || true
    case "${cmd}" in
        ""|help|-h|--help)
            usage
            exit 0
            ;;
        aarch64|riscv64|x86_64)
            ARCH="$cmd"
            ROOTFS_ARCH="${ARCH}"
            ROOTFS_STAGE_PREFIX="qemu-rootfs-${ARCH}"
            if [[ $# -eq 0 || "${1:-}" == "help" || "${1:-}" == "-h" || "${1:-}" == "--help" || "${1:-}" == --* ]]; then
                QEMU_ARCH="${ARCH}" usage
                exit 0
            fi
            OS="$1"
            shift 1 || true
            rootfs_parse_build_args "$@"
            rootfs_apply_default_builders "${OS}"
            trap '[[ -n "${ROOTFS_STAGE_DIR:-}" && -d "${ROOTFS_STAGE_DIR}" ]] && rm -rf "${ROOTFS_STAGE_DIR}"' EXIT
            case "${OS}" in
                linux)
                    linux "${BUILD_ARGS[@]}"
                    ;;
                arceos)
                    arceos "${BUILD_ARGS[@]}"
                    ;;
                nimbos)
                    nimbos "${BUILD_ARGS[@]}"
                    ;;
                zephyr)
                    zephyr "${BUILD_ARGS[@]}"
                    ;;
                freertos)
                    freertos "${BUILD_ARGS[@]}"
                    ;;
                all)
                    linux "${BUILD_ARGS[@]}"
                    arceos "${BUILD_ARGS[@]}"
                    nimbos "${BUILD_ARGS[@]}"
                    if [[ "${ARCH}" == "aarch64" ]]; then
                        zephyr "${BUILD_ARGS[@]}"
                        freertos "${BUILD_ARGS[@]}"
                    fi
                    ;;
                clean)
                    linux "clean"
                    arceos "clean"
                    nimbos "clean"
                    if [[ "${ARCH}" == "aarch64" ]]; then
                        zephyr "clean"
                        freertos "clean"
                    fi
                    rootfs_clean_generated_outputs
                    ;;
                *)
                    die "Unknown os: ${OS} (supported: linux, arceos, nimbos, zephyr, freertos, all)"
                    ;;
            esac
            if [[ "${OS}" != "clean" ]]; then
                rootfs_ensure_stage_dir
                rootfs_stage_guest_tree "${ROOTFS_STAGE_DIR}" "$(qemu_arch_images_dir "${ARCH}")"
                rootfs_finalize_builders
            fi
            trap - EXIT
            [[ -n "${ROOTFS_STAGE_DIR:-}" && -d "${ROOTFS_STAGE_DIR}" ]] && rm -rf "${ROOTFS_STAGE_DIR}"
            ;;
        all)
            if [[ $# -eq 0 || "${1:-}" == "help" || "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
                QEMU_ARCH="all" usage
                exit 0
            fi

            if [[ "${1:-}" == --* ]]; then
                OS="all"
            else
                OS="$1"
                shift 1 || true
            fi

            for arch in aarch64 riscv64 x86_64; do
                "$0" "$arch" "${OS}" "$@" || { echo "[ERROR] $arch build failed" >&2; exit 1; }
            done
            ;;
        clean)
            for arch in aarch64 riscv64 x86_64; do
                "$0" "$arch" "clean" || { echo "[ERROR] $arch build failed" >&2; exit 1; }
            done
            ;;
        *)
        die "Unknown command: $cmd" >&2
        ;;
    esac
fi
